DB_FILE = 'blog_data.db'

def init_db():
    conn = sqlite3.connect(DB_FILE)
    c = conn.cursor()

    # 用户表
    c.execute('''CREATE TABLE IF NOT EXISTS users (
                    username TEXT PRIMARY KEY,
                    password TEXT,
                    nickname TEXT,
                    avatar BLOB,
                    role TEXT,
                    is_active INTEGER
                )''')

    # 文章/作品表
    c.execute('''CREATE TABLE IF NOT EXISTS posts (
                    id INTEGER PRIMARY KEY AUTOINCREMENT,
                    category TEXT,
                    title TEXT,
                    content TEXT,
                    image BLOB,
                    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
                )''')

    # 评论表
    c.execute('''CREATE TABLE IF NOT EXISTS comments (
                    id INTEGER PRIMARY KEY AUTOINCREMENT,
                    post_id INTEGER,
                    username TEXT,
                    content TEXT,
                    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                    FOREIGN KEY(post_id) REFERENCES posts(id),
                    FOREIGN KEY(username) REFERENCES users(username)
                )''')

    # 创建默认管理员 (如果不存在)
    c.execute("SELECT * FROM users WHERE username = 'admin'")
    if not c.fetchone():
        pwd_hash = hashlib.sha256("admin123".encode()).hexdigest()
        c.execute("INSERT INTO users (username, password, nickname, role, is_active) VALUES (?, ?, ?, ?, ?)",
                  ('admin', pwd_hash, 'Admin', 'admin', 1))

    conn.commit()
    conn.close()

init_db()

# --- 辅助函数 ---
def make_hash(password):
    return hashlib.sha256(password.encode()).hexdigest()

def check_hashes(password, hashed_text):
    if make_hash(password) == hashed_text:
        return True
    return False

def get_avatar(username):
    conn = sqlite3.connect(DB_FILE)
    c = conn.cursor()
    c.execute("SELECT avatar FROM users WHERE username=?", (username,))
    data = c.fetchone()
    conn.close()
    if data and data[0]:
        return data[0]
    return None

def save_image_to_bytes(uploaded_file):
    if uploaded_file is None:
        return None
    bytes_data = uploaded_file.getvalue()
    return bytes_data

