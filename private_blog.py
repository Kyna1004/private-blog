def sidebar_user_system():
    st.sidebar.title("🔐 Account")

    if 'logged_in' not in st.session_state:
        st.session_state.logged_in = False
        st.session_state.role = 'guest'
        st.session_state.username = ''

    if not st.session_state.logged_in:
        tab1, tab2 = st.sidebar.tabs(["Login", "Register"])

        with tab1:
            username = st.text_input("Username", key="login_user")
            password = st.text_input("Password", type='password', key="login_pwd")
            if st.button("Login"):
                conn = sqlite3.connect(DB_FILE)
                c = conn.cursor()
                c.execute('SELECT password, role, is_active, nickname FROM users WHERE username = ?', (username,))
                data = c.fetchone()
                conn.close()

                if data:
                    if check_hashes(password, data[0]):
                        if data[2] == 1:
                            st.session_state.logged_in = True
                            st.session_state.username = username
                            st.session_state.role = data[1]
                            st.session_state.nickname = data[3]
                            st.success(f"欢迎回来, {data[3]}")
                            st.rerun()
                        else:
                            st.error("账号等待管理员审核中。")
                    else:
                        st.error("密码错误")
                else:
                    st.error("用户不存在")

        with tab2:
            new_user = st.text_input("New Username", key="reg_user")
            new_pwd = st.text_input("New Password", type='password', key="reg_pwd")
            new_nick = st.text_input("Nickname", key="reg_nick")

            if st.button("Register Application"):
                conn = sqlite3.connect(DB_FILE)
                c = conn.cursor()
                c.execute('SELECT username FROM users WHERE username = ?', (new_user,))
                if c.fetchone():
                    st.error("用户名已存在")
                else:
                    c.execute('INSERT INTO users (username, password, nickname, role, is_active) VALUES (?, ?, ?, ?, ?)',
                              (new_user, make_hash(new_pwd), new_nick, 'user', 0)) # 默认 is_active = 0
                    conn.commit()
                    st.success("注册申请已提交，请联系管理员审核。")
                conn.close()

    else:
        # 已登录状态
        avatar_bytes = get_avatar(st.session_state.username)
        if avatar_bytes:
            st.sidebar.image(avatar_bytes, width=100, caption=st.session_state.nickname)
        else:
            st.sidebar.markdown(f"**👤 {st.session_state.nickname}**")

        st.sidebar.markdown(f"Role: `{st.session_state.role}`")

        # 用户设置 (修改头像/密码)
        with st.sidebar.expander("Settings"):
            new_avatar = st.file_uploader("Upload Avatar", type=['png', 'jpg'])
            if new_avatar:
                if st.button("Update Avatar"):
                    img_bytes = save_image_to_bytes(new_avatar)
                    conn = sqlite3.connect(DB_FILE)
                    c = conn.cursor()
                    c.execute("UPDATE users SET avatar=? WHERE username=?", (img_bytes, st.session_state.username))
                    conn.commit()
                    conn.close()
                    st.success("头像已更新")
                    st.rerun()

        if st.sidebar.button("Logout"):
            st.session_state.logged_in = False
            st.session_state.role = 'guest'
            st.session_state.username = ''
            st.rerun()

    # --- 管理员面板 (仅管理员可见) ---
    if st.session_state.logged_in and st.session_state.role == 'admin':
        st.sidebar.markdown("---")
        st.sidebar.subheader("🛠 Admin Panel")

        # 用户审批
        with st.sidebar.expander("User Approval"):
            conn = sqlite3.connect(DB_FILE)
            c = conn.cursor()
            c.execute("SELECT username, nickname FROM users WHERE is_active=0")
            pending_users = c.fetchall()

            if not pending_users:
                st.info("没有待审核用户")
            else:
                for u in pending_users:
                    col1, col2 = st.columns([2,1])
                    col1.text(f"{u[1]} ({u[0]})")
                    if col2.button("Approve", key=f"app_{u[0]}"):
                        c.execute("UPDATE users SET is_active=1 WHERE username=?", (u[0],))
                        conn.commit()
                        st.success(f"已通过 {u[0]}")
                        st.rerun()
            conn.close()

        # 内容发布入口
        if st.sidebar.checkbox("Show Publisher Tool"):
            st.sidebar.info("请在主页面上方查看发布工具")

