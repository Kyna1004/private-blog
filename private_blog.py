def render_content_feed(category):
    st.title(f"📂 {category}")

    # --- 管理员发布区域 ---
    if st.session_state.get('logged_in') and st.session_state.role == 'admin':
        with st.expander(f"➕ New {category} Post", expanded=False):
            with st.form(f"new_{category}_form"):
                new_title = st.text_input("Title")
                new_content = st.text_area("Content (Markdown supported)", height=150)
                uploaded_img = st.file_uploader("Cover Image (Optional)", type=['png', 'jpg', 'jpeg'])
                submit = st.form_submit_button("Publish")

                if submit and new_title and new_content:
                    img_data = save_image_to_bytes(uploaded_img)
                    conn = sqlite3.connect(DB_FILE)
                    c = conn.cursor()
                    c.execute("INSERT INTO posts (category, title, content, image) VALUES (?, ?, ?, ?)",
                              (category, new_title, new_content, img_data))
                    conn.commit()
                    conn.close()
                    st.success("发布成功！")
                    st.rerun()

    # --- 内容展示 ---
    conn = sqlite3.connect(DB_FILE)
    c = conn.cursor()
    c.execute("SELECT id, title, content, created_at, image FROM posts WHERE category=? ORDER BY created_at DESC", (category,))
    posts = c.fetchall()
    conn.close()

    if not posts:
        st.caption("这里还是一片荒原...")

    for post in posts:
        pid, title, content, date, img_data = post

        # 容器开始
        st.markdown(f'<div class="notion-card">', unsafe_allow_html=True)

        st.subheader(title)
        st.caption(f"📅 {date}")

        if img_data:
            st.image(img_data, use_column_width=True)

        st.markdown(content)

        # 评论区开关
        with st.expander(f"💬 Comments"):
            # 显示已有评论
            conn = sqlite3.connect(DB_FILE)
            c = conn.cursor()
            c.execute("""
                SELECT comments.content, users.nickname, comments.created_at, users.avatar
                FROM comments
                JOIN users ON comments.username = users.username
                WHERE post_id=? ORDER BY created_at DESC
            """, (pid,))
            comments = c.fetchall()
            conn.close()

            for cmt in comments:
                c_content, c_nick, c_date, c_avatar = cmt
                # 简单渲染评论
                st.markdown(
                    f"""
                    <div class="comment-box">
                        <strong>{c_nick}</strong> <span style="color:#888; font-size:0.8em;">{c_date}</span><br>
                        {c_content}
                    </div>
                    """, unsafe_allow_html=True
                )

            # 发布评论 (仅登录用户)
            if st.session_state.get('logged_in'):
                comment_txt = st.text_input("Write a comment...", key=f"cmt_in_{pid}")
                if st.button("Send", key=f"btn_cmt_{pid}"):
                    if comment_txt:
                        conn = sqlite3.connect(DB_FILE)
                        c = conn.cursor()
                        c.execute("INSERT INTO comments (post_id, username, content) VALUES (?, ?, ?)",
                                  (pid, st.session_state.username, comment_txt))
                        conn.commit()
                        conn.close()
                        st.rerun()
            else:
                st.caption("登录后可发表评论")

        st.markdown('</div>', unsafe_allow_html=True) # 容器结束

def render_gallery():
    st.title("🎨 Gallery")

    # --- 管理员上传图片 ---
    if st.session_state.get('logged_in') and st.session_state.role == 'admin':
        with st.expander("➕ Upload Art", expanded=False):
            with st.form("gallery_upload"):
                title = st.text_input("Title")
                desc = st.text_area("Description")
                art_file = st.file_uploader("Image File", type=['png', 'jpg', 'jpeg'])
                submit = st.form_submit_button("Upload to Gallery")

                if submit and art_file:
                    img_data = save_image_to_bytes(art_file)
                    conn = sqlite3.connect(DB_FILE)
                    c = conn.cursor()
                    c.execute("INSERT INTO posts (category, title, content, image) VALUES (?, ?, ?, ?)",
                              ('Gallery', title, desc, img_data))
                    conn.commit()
                    conn.close()
                    st.success("上传成功")
                    st.rerun()

    # --- 瀑布流/网格展示 ---
    conn = sqlite3.connect(DB_FILE)
    c = conn.cursor()
    c.execute("SELECT id, title, content, image FROM posts WHERE category='Gallery' ORDER BY created_at DESC")
    items = c.fetchall()
    conn.close()

    if items:
        # 使用列布局模拟网格
        cols = st.columns(3)
        for idx, item in enumerate(items):
            pid, title, content, img_data = item
            with cols[idx % 3]:
                if img_data:
                    st.image(img_data, use_column_width=True)
                st.caption(f"**{title}**")
                if content:
                    st.caption(content)
                st.markdown("---")
    else:
        st.caption("画廊暂时没有展品。")

